-- ============================================================
-- words 表防重唯一索引 (v1.26.0)
--
-- 目的: 从数据库层兜底, 杜绝任何写入路径(导入/单条新增/同步/脚本)
--       产生「同一用户 + 完全相同词头」的重复词。
--
-- 设计: UNIQUE(user_id, word) —— 大小写敏感。
--   ✅ 阻止 fall / fall 这类真重复
--   ✅ 允许 AD / ad、March / march 这类大小写不同的独立词共存
--   ✅ 幂等加索引; 加之前全表已确认零精确重复
--
-- 说明: Postgres 唯一索引中 NULL 互不相等, 因此 user_id IS NULL 的
--       历史兼容行不受此约束(不影响正常用户数据)。
-- ============================================================

CREATE UNIQUE INDEX IF NOT EXISTS uq_words_user_word
  ON words (user_id, word);

-- 验证: 若存在重复会导致建索引失败, 上面的语句成功即表示数据干净。
